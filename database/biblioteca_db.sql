/*
===============================================================================
                        BIBLIOTECA API
                 SCRIPT DE BASE DE DATOS POSTGRESQL
===============================================================================

Proyecto        : Biblioteca API
Base de datos   : biblioteca_db
Motor           : PostgreSQL
Schema          : public
Unidad didáctica: Desarrollo de los Componentes del Negocio

Descripción:
Este script documenta y permite reconstruir la estructura relacional utilizada
por la API REST de biblioteca desarrollada con Spring Boot, JPA e Hibernate.

IMPORTANTE:
- Crear previamente la base de datos "biblioteca_db".
- Ejecutar este script conectado a dicha base de datos.
- La aplicación también puede crear/actualizar estas tablas automáticamente
  mediante Hibernate con spring.jpa.hibernate.ddl-auto=update.

Orden de creación:
1. roles
2. usuarios
3. libros
4. usuario_roles
5. prestamos

===============================================================================
*/


/* =============================================================================
   0. CREACIÓN DE LA BASE DE DATOS
   -----------------------------------------------------------------------------
   Ejecutar esta instrucción desde otra base, por ejemplo "postgres", si la
   base de datos todavía no existe. Luego conectarse a biblioteca_db antes de
   continuar con el resto del script.
   =============================================================================

CREATE DATABASE biblioteca_db;

*/


/* =============================================================================
   1. TABLA: roles
   -----------------------------------------------------------------------------
   Almacena los roles de seguridad disponibles en la aplicación.
   Valores permitidos:
   - ROLE_ADMIN
   - ROLE_USUARIO
   ============================================================================= */

CREATE TABLE IF NOT EXISTS public.roles
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nombre varchar(30) NOT NULL,

    CONSTRAINT roles_pkey
        PRIMARY KEY (id),

    CONSTRAINT roles_nombre_unique
        UNIQUE (nombre),

    CONSTRAINT roles_nombre_check
        CHECK (nombre IN ('ROLE_ADMIN', 'ROLE_USUARIO'))
);

ALTER TABLE IF EXISTS public.roles
    OWNER TO postgres;


/* =============================================================================
   2. TABLA: usuarios
   -----------------------------------------------------------------------------
   Almacena las cuentas registradas en el sistema.
   El correo electrónico es único.
   La contraseña se almacena cifrada mediante BCrypt desde la aplicación.
   ============================================================================= */

CREATE TABLE IF NOT EXISTS public.usuarios
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email varchar(150) NOT NULL,
    nombre varchar(100) NOT NULL,
    password varchar(255) NOT NULL,

    CONSTRAINT usuarios_pkey
        PRIMARY KEY (id),

    CONSTRAINT usuarios_email_unique
        UNIQUE (email)
);

ALTER TABLE IF EXISTS public.usuarios
    OWNER TO postgres;


/* =============================================================================
   3. TABLA: libros
   -----------------------------------------------------------------------------
   Almacena la información de los libros de la biblioteca.
   El ISBN es único y el campo disponible indica si el libro puede prestarse.
   ============================================================================= */

CREATE TABLE IF NOT EXISTS public.libros
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    autor varchar(100) NOT NULL,
    categoria varchar(80) NOT NULL,
    disponible boolean NOT NULL,
    isbn varchar(20) NOT NULL,
    titulo varchar(150) NOT NULL,

    CONSTRAINT libros_pkey
        PRIMARY KEY (id),

    CONSTRAINT libros_isbn_unique
        UNIQUE (isbn)
);

ALTER TABLE IF EXISTS public.libros
    OWNER TO postgres;


/* =============================================================================
   4. TABLA: usuario_roles
   -----------------------------------------------------------------------------
   Tabla intermedia que implementa la relación muchos a muchos (N:M)
   entre usuarios y roles.

   usuarios N:M roles
   ============================================================================= */

CREATE TABLE IF NOT EXISTS public.usuario_roles
(
    usuario_id bigint NOT NULL,
    rol_id bigint NOT NULL,

    CONSTRAINT usuario_roles_pkey
        PRIMARY KEY (usuario_id, rol_id),

    CONSTRAINT usuario_roles_usuario_fk
        FOREIGN KEY (usuario_id)
        REFERENCES public.usuarios (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,

    CONSTRAINT usuario_roles_rol_fk
        FOREIGN KEY (rol_id)
        REFERENCES public.roles (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

ALTER TABLE IF EXISTS public.usuario_roles
    OWNER TO postgres;


/* =============================================================================
   5. TABLA: prestamos
   -----------------------------------------------------------------------------
   Registra los préstamos y devoluciones realizados en la biblioteca.

   Relaciones:
   - Un usuario puede tener varios préstamos (1:N).
   - Un libro puede aparecer en varios préstamos a lo largo del tiempo (1:N).

   Estados permitidos:
   - PRESTADO
   - DEVUELTO
   ============================================================================= */

CREATE TABLE IF NOT EXISTS public.prestamos
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    estado varchar(20) NOT NULL,
    fecha_devolucion date,
    fecha_prestamo date NOT NULL,
    libro_id bigint NOT NULL,
    usuario_id bigint NOT NULL,

    CONSTRAINT prestamos_pkey
        PRIMARY KEY (id),

    CONSTRAINT prestamos_usuario_fk
        FOREIGN KEY (usuario_id)
        REFERENCES public.usuarios (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,

    CONSTRAINT prestamos_libro_fk
        FOREIGN KEY (libro_id)
        REFERENCES public.libros (id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,

    CONSTRAINT prestamos_estado_check
        CHECK (estado IN ('PRESTADO', 'DEVUELTO'))
);

ALTER TABLE IF EXISTS public.prestamos
    OWNER TO postgres;


/* =============================================================================
   6. DATOS INICIALES: roles
   -----------------------------------------------------------------------------
   Inserta los roles principales únicamente si todavía no existen.
   ============================================================================= */

INSERT INTO public.roles (nombre)
VALUES ('ROLE_ADMIN')
ON CONFLICT (nombre) DO NOTHING;

INSERT INTO public.roles (nombre)
VALUES ('ROLE_USUARIO')
ON CONFLICT (nombre) DO NOTHING;


/* =============================================================================
   7. CONSULTAS DE VERIFICACIÓN
   -----------------------------------------------------------------------------
   Estas consultas permiten comprobar rápidamente que las tablas existen
   y consultar los datos almacenados.
   ============================================================================= */

SELECT * FROM public.roles;
SELECT * FROM public.usuarios;
SELECT * FROM public.libros;
SELECT * FROM public.usuario_roles;
SELECT * FROM public.prestamos;


/* =============================================================================
   FIN DEL SCRIPT
   ============================================================================= */
